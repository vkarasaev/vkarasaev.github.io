// Лёгкая типографика для русских текстов лендингов направлений.
// Ничего не переписывает: только заменяет обычные пробелы на неразрывные там,
// где перенос строки выглядит неряшливо (висячие предлоги, тире-дефис, числа).

const NBSP = ' ';

// Короткие предлоги, союзы и частицы, после которых строку рвать не стоит.
const SHORT =
  'в|во|и|а|с|со|к|ко|о|об|у|я|на|не|ни|но|по|за|из|от|до|то|для|или|без|при|под|над|про|вы|мы|он|их|что|как';

const shortWord = new RegExp(`(?<=^|[\\s(«„"${NBSP}])(${SHORT}) `, 'giu');

export function typograf(input: string): string {
  return input
    // «слово - слово»: дефис в роли тире не уходит в начало строки
    .replace(/ - /g, `${NBSP}- `)
    // 5 000, 2 500
    .replace(/(\d) (?=\d{3}(?!\d))/g, `$1${NBSP}`)
    // 55 минут, 5 000 ₽, 60 €
    .replace(/(\d) (?=[₽€]|минут|лет|год)/g, `$1${NBSP}`)
    .replace(shortWord, `$1${NBSP}`);
}

// 1 статья, 3 статьи, 7 статей
export function plural(n: number, forms: [string, string, string]): string {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return forms[0];
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return forms[1];
  return forms[2];
}
